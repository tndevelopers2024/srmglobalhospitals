    <p>Chronic esophageal ulcers can sometimes cause halitosis or a metallic taste in the mouth. These symptoms may result from stomach acid regurgitation or bacterial infection around the ulcer. If bad breath continues despite regular oral hygiene, it may be worth checking for digestive tract issues.</p>

