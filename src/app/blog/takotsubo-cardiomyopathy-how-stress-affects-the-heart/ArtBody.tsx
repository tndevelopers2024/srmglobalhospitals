    <p>Because stress hormones can have a sudden impact on the heart, some patients experience irregular heart rhythms. These may include fast heartbeats (tachycardia), skipped beats (palpitations), or even life-threatening arrhythmias that need electrical monitoring or antiarrhythmic medications.</p>

